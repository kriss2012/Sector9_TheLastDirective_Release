"""Space-lobby corridor layout (pure data, no pygame import).

Top-down map (x -> east, y -> south). '#' wall, 'Z' star-window, 'T' terminal,
'D' door, '.' floor. Spawn is the west end of the central corridor.

        x: 0         1         2
           0123456789012345678901234567
   y0      #########T###############ZZ#      T Mission Board (9,0)
   y1      #...#.........#.......#....#      N: Supply | Mission Control | Annex | Observation
   y2      #...#.........#.......#....#
   y3      ##D###Z##D####Z####D###DZ###      north doors x = 2, 9, 19, 23
   y4      #..........................#
   y5      #..........................D      Launch Airlock (27,5)
   y6      #..........................#
   y7      ##D###T##D####Z####D########      south doors x = 2, 9, 19 ; Power Node T (6,7)
   y8      #...#.........#.........####      S: Crew Quarters | Airlock Bay | Hangar
   y9      #...#.........#.........####
   y10     ############################

(Generated by build_grid(); a unit test keeps the doors in sync with DOOR_CELLS.)

Mission chain (every lock type is used):
  Supply Locker (open)  -> Level-1 Keycard
  Mission Control (key) -> accept mission at the board, learn the annex code
  Engineering Annex (keypad 7319) -> Power Cell
  Power Node (corridor) -> restore power
  Airlock Bay (powered door) -> Level-2 Keycard
  Hangar Gate (key) -> Mission Data Chip  => CONTAINMENT LOCKDOWN
  Launch Airlock (needs chip + lockdown over) -> launch mission
"""
from src.door_system import Door, DoorSystem, LOCK_NONE, LOCK_KEY, LOCK_FLAG, LOCK_CODE

LOBBY_CHAPTER_ID = 7
WIDTH, HEIGHT = 28, 11
SPAWN = (1.5, 5.5, 0.0)

ANNEX_CODE = "7319"
LOCKDOWN_SECONDS = 12.0

ITEM_KEY1 = "Level-1 Keycard"
ITEM_KEY2 = "Level-2 Keycard"
ITEM_CELL = "Power Cell"
ITEM_CHIP = "Mission Data Chip"

FLAG_ACCEPTED = "lobby_mission_accepted"
FLAG_POWER = "power_online"
FLAG_CHIP = "lobby_chip_taken"
FLAG_LAUNCH_READY = "lobby_launch_ready"

# Room interiors: (x0, x1, y0, y1) inclusive
ROOMS_NORTH = {"supply": (1, 3), "mission_control": (5, 13), "annex": (15, 21), "observation": (23, 26)}
ROOMS_SOUTH = {"crew": (1, 3), "airlock_bay": (5, 13), "hangar": (15, 23)}
NORTH_Y = (1, 2)
SOUTH_Y = (8, 9)
CORRIDOR_Y = (4, 5, 6)

# Wall texture per region (keys of TextureGenerator textures)
STYLE_ORANGE = "lobby_orange"   # concept image 1: white/orange "Level 07" corridor
STYLE_SILVER = "lobby_silver"   # concept image 2: blue-silver corridor
STYLE_WHITE = "lobby_white"     # concept image 3: white "SPACE-CORPS" tube


def build_grid():
    g = [['#'] * WIDTH for _ in range(HEIGHT)]
    for y in CORRIDOR_Y:
        for x in range(1, WIDTH - 1):
            g[y][x] = '.'
    for name, (x0, x1) in ROOMS_NORTH.items():
        for y in NORTH_Y:
            for x in range(x0, x1 + 1):
                g[y][x] = '.'
    for name, (x0, x1) in ROOMS_SOUTH.items():
        for y in SOUTH_Y:
            for x in range(x0, x1 + 1):
                g[y][x] = '.'
    # Door cells (the DoorSystem owns their state; these are the closed defaults)
    for (x, y) in [(2, 3), (9, 3), (19, 3), (23, 3), (2, 7), (9, 7), (19, 7), (27, 5)]:
        g[y][x] = 'D'
    # Terminals
    g[0][9] = 'T'     # Mission Board
    g[7][6] = 'T'     # Auxiliary Power Node
    # Star windows
    for (x, y) in [(14, 3), (24, 3), (14, 7), (6, 3), (25, 0), (26, 0)]:
        g[y][x] = 'Z'
    return ["".join(r) for r in g]


def wall_style(x, y):
    """Texture style for a wall cell at (x, y)."""
    if 3 <= y <= 7:                       # corridor-facing walls
        return STYLE_ORANGE if x < 14 else STYLE_SILVER
    north = y < 3
    if x <= 4:
        return STYLE_WHITE
    if x <= 14:
        return STYLE_SILVER if north else STYLE_WHITE
    if x <= 22:
        return STYLE_ORANGE
    return STYLE_SILVER


def build_wall_tex_map(grid):
    m = {}
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch == '#':
                m[(x, y)] = wall_style(x, y)
    return m


def build_doors(unlocked_ids=()):
    doors = [
        Door("supply", (2, 3), "SUPPLY LOCKER", LOCK_NONE),
        Door("mission_control", (9, 3), "MISSION CONTROL", LOCK_KEY, requires=ITEM_KEY1),
        Door("annex", (19, 3), "ENGINEERING ANNEX", LOCK_CODE, code=ANNEX_CODE),
        Door("observation", (23, 3), "OBSERVATION LOUNGE", LOCK_NONE),
        Door("crew", (2, 7), "CREW QUARTERS", LOCK_NONE),
        Door("airlock_bay", (9, 7), "AIRLOCK BAY", LOCK_FLAG, requires=FLAG_POWER,
             deny_message="NO POWER - AUXILIARY GRID OFFLINE"),
        Door("hangar", (19, 7), "HANGAR GATE", LOCK_KEY, requires=ITEM_KEY2),
        Door("launch", (27, 5), "LAUNCH AIRLOCK", LOCK_FLAG, requires=FLAG_LAUNCH_READY,
             deny_message="LAUNCH AIRLOCK SEALED - MISSION DATA REQUIRED", launch=True, auto_close=None),
    ]
    for d in doors:
        if d.id in unlocked_ids:
            d.unlock()
    return DoorSystem(doors)


